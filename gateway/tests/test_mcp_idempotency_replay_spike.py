def _history_functions(revision: str, path: str, names: set[str]) -> dict:
    """Execute only selected function definitions from read-only local history."""
    source = subprocess.run(
        ["git", "show", f"{revision}:{path}"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    nodes = [
        node
        for node in ast.parse(source).body
        if isinstance(node, ast.FunctionDef) and node.name in names
    ]
    assert {node.name for node in nodes} == names
    namespace = {
        "json": json,
        "hashlib": hashlib,
        "Decimal": Decimal,
        "datetime": datetime,
        "timezone": timezone,
        "Any": Any,
        "DERIVED_KEY_PREFIX": "mcp-retry-",
    }
    exec(compile(ast.Module(body=nodes, type_ignores=[]), path, "exec"), namespace)
    return namespace


def _key(revision: str, kind: str, wallet: dict, permit_id: str, args: dict) -> str:
    if kind == "client":
        # Caller-owned key is opaque and independent of canonical JSON.
        return "case-11-client"
    if kind == "gov":
        functions = _history_functions(
            revision, GOVERNED, {"derive_governed_idempotency_key"}
        )
        return functions["derive_governed_idempotency_key"](
            permit_id=permit_id, tool_name="echo_charge", arguments=args
        )
    functions = _history_functions(
        revision, RETRY, {"canonical_arguments", "derive_retry_identity", "slot_key"}
    )
    identity = functions["derive_retry_identity"](
        wallet_id=wallet["agent_wallet_id"],
        key_id=wallet["key_id"],
        principal="",
        tool_name="echo_charge",
        arguments=args,
    )
    return functions["slot_key"](identity, window_seconds=60, bucket=0, attempt=0)


class CrossDeployReplayMissing(AssertionError):
    """Desired replay contract failed after current behavior was measured."""


@pytest.mark.xfail(
    strict=True,
    raises=CrossDeployReplayMissing,
    reason="current_behavior: unchanged keys conflict with pre-JCS request hashes; "
    "measurement only, no fix (C.Lee approval required)",
)
@pytest.mark.anyio
@pytest.mark.parametrize("key_kind", ["client", "gov", "mcp-retry"])
async def test_case_11_current_behavior(
    key_kind: str, clean_database: None, monkeypatch: pytest.MonkeyPatch
) -> None:
    def no_network(*args: Any, **kwargs: Any) -> None:
        raise AssertionError("case 11 must remain offline")

    monkeypatch.setattr(socket.socket, "connect", no_network)
    monkeypatch.setattr(socket, "getaddrinfo", no_network)
    legacy = _history_functions(
        PARENT, "gateway/app/services/signing_keys.py", {"canonical_json"}
    )["canonical_json"]
    arguments = json.loads('{"amount":1.10,"message":"café"}')
    assert legacy(arguments) != canonical_json(arguments)
    executor = FakeUpstreamExecutor("success")
    registry = get_service_registry()
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        wallet = await provision_agent_wallet(client)
        registry.register_upstream(
            service_id="echo_charge",
            name="echo_charge",
            description="Case 11 counting upstream",
            category=ServiceCategory.AGENT_COMMS,
            executor=executor,
            input_schema={"type": "object"},
            output_schema=None,
            credits_per_unit=2.0,
            upstream_tool_name="echo_charge",
            upstream_origin="https://partner.example",
        )
        try:
            permit = await create_tool_permit(
                client,
                wallet_id=wallet["agent_wallet_id"],
                key_id=wallet["key_id"],
                tool_name="echo_charge",
            )
            old_key = _key(PARENT, key_kind, wallet, permit["permit_id"], arguments)
            new_key = _key(BASE, key_kind, wallet, permit["permit_id"], arguments)
            body = _call_body(
                tool_name="echo_charge",
                wallet_id=wallet["agent_wallet_id"],
                permit_id=permit["permit_id"],
                idempotency_key=old_key,
            )
            body["params"]["arguments"] = arguments
            with monkeypatch.context() as before_deploy:
                before_deploy.setattr(
                    idempotency,
                    "sha256_hex",
                    lambda payload: hashlib.sha256(
                        legacy(payload).encode()
                    ).hexdigest(),
                )
                first = await client.post(
                    "/mcp/messages", json=body, headers=wallet["agent_headers"]
                )
            assert first.status_code == 200, first.text
            first_receipt = first.json()["result"]["receipt"]
            assert first_receipt["outcome"] == "success"
            body["params"]["mcpContext"]["idempotency_key"] = new_key
            retry = await client.post(
                "/mcp/messages", json=body, headers=wallet["agent_headers"]
            )
            assert retry.status_code == 200, retry.text
            retry_body = retry.json()
            retry_receipt = retry_body.get("result", {}).get("receipt")
            async with get_session_factory()() as session:
                receipt_ids = list(
                    (await session.scalars(select(ReceiptModel.receipt_id))).all()
                )
            # These measured facts must pass before the desired-contract xfail.
            assert old_key == new_key
            assert executor.dispatch_count == 1
            assert retry_body["error"]["message"] == "idempotency_key_reused"
            assert retry_body["error"]["code"] == -32603
            assert retry_receipt is None
            assert receipt_ids == [first_receipt["receipt_id"]]
            # Only this exception is eligible for the strict expected failure.
            with_desired_replay = (
                old_key == new_key
                and executor.dispatch_count == 1
                and retry_receipt is not None
                and retry_receipt["receipt_id"] == first_receipt["receipt_id"]
            )
            if not with_desired_replay:
                raise CrossDeployReplayMissing(
                    "cross-deploy retry did not return original receipt"
                )
        finally:
            registry.unregister_local("echo_charge")
