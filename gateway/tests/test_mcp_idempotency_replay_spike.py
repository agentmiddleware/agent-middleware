def derive_retry_identity(
    *,
    wallet_id: str,
    key_id: str | None,
    principal: str,
    tool_name: str,
    arguments: Any,
) -> str:
    """Time-independent identity of one logical unkeyed call."""
    material = "\x1f".join(
        [
            "v2",
            wallet_id,
            key_id or "",
            principal,
            tool_name,
            canonical_arguments(arguments),
        ]
    )
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


