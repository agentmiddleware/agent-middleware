// Minimal PostHog capture API client. The browser SDK enriches event properties
// automatically; this client sends only the marketing site's explicit contract.
// https://posthog.com/docs/api/capture
(function () {
  "use strict";

  const pending = window.amwPosthog;
  const config = pending?.config;
  if (!config?.key || config.host !== "https://us.i.posthog.com") return;

  const allowedEvents = new Set(["$pageview", "booking_click", "demo_key_click", "email_click", "proof_click"]);
  const utmKeys = ["utm_source", "utm_medium", "utm_campaign", "utm_content", "utm_term"];
  const registered = {};
  // Required ingestion identity is generated by the browser and lasts only for
  // this page. It is transport metadata, never an event property or stored ID.
  let distinctId;

  function utms(properties) {
    const result = {};
    for (const key of utmKeys) {
      const value = properties?.[key];
      if (typeof value !== "string") continue;
      const trimmed = value.trim();
      if (trimmed && !trimmed.includes("@")) result[key] = trimmed.slice(0, 128);
    }
    return result;
  }

  const client = {
    register(properties) {
      Object.assign(registered, utms(properties));
    },
    capture(event, properties) {
      if (!allowedEvents.has(event)) return;
      const isPageview = event === "$pageview";
      if (!isPageview && !/^[a-z0-9_-]{1,80}$/.test(properties?.cta_id || "")) return;
      // Rebuild at the transport boundary, so extra fields never reach PostHog.
      const page = typeof properties?.page === "string" ? properties.page.split(/[?#]/, 1)[0] : "";
      if (!page.startsWith("/") || page.startsWith("//")) return;
      const safeProperties = {
        ...registered,
        ...(isPageview ? {} : utms(properties)),
        product: "AMW",
        page,
        $process_person_profile: false,
        $geoip_disable: true,
        ...(isPageview ? {} : { cta_id: properties.cta_id }),
      };
      try {
        distinctId ||= window.crypto.randomUUID();
        const request = fetch(`${config.host}/i/v0/e/`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            api_key: config.key,
            event,
            distinct_id: distinctId,
            properties: safeProperties,
          }),
          credentials: "omit",
          referrerPolicy: "no-referrer",
          keepalive: true,
        });
        request.catch(function () {});
      } catch {
        // Missing browser APIs or blocked requests never interfere with a CTA.
      }
    },
  };
  window.amwPosthog = client;
  for (const [method, ...args] of pending.queue) client[method](...args);
  pending.queue.length = 0;
})();
